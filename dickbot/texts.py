from html import escape


def days_word(n: int) -> str:
    if 11 <= n % 100 <= 14:
        return "дней"
    return {1: "день", 2: "дня", 3: "дня", 4: "дня"}.get(n % 10, "дней")


def b(x) -> str:
    return f"<b>{x}</b>"


def name(n: str) -> str:
    return escape(n or "???")


def mention(uid: int, n: str) -> str:
    return f'<b><a href="tg://user?id={uid}">{name(n)}</a></b>'


def time_till_next_day(hours: int, minutes: int) -> str:
    return f"\n\nСледующая попытка через {b(hours)} ч. {b(minutes)} мин."


